"""Problem 39 — Reverse a String
Task:
Ask the user to enter a string.
Reverse the string and print it."""

# Pseudocode
# Get input from user
# Reverse the string using slicing
# Print the reversed string

# Ask for user input
s = input("Enter a string: ")

# Reverse string
reversed_s = s[::-1]

# Print result
print("Reversed string:", reversed_s)
